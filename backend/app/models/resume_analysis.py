import uuid
from sqlalchemy import Column, Integer, String, Boolean, DateTime, ForeignKey, Text, JSON
from sqlalchemy.orm import relationship
from app.core.database import Base
from app.models.base import TimestampMixin, UUIDMixin


class ResumeAnalysis(Base, UUIDMixin, TimestampMixin):
    """
    AI-Powered Resume Analysis generated by Google Gemini.
    Strictly isolated per user and linked to the specific authenticated Resume.
    """
    __tablename__ = "resume_analyses"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    resume_id = Column(Integer, ForeignKey("resumes.id", ondelete="SET NULL"), nullable=True, index=True)
    candidate_id = Column(Integer, ForeignKey("candidates.id", ondelete="SET NULL"), nullable=True, index=True)

    # Role & Seniority
    target_role = Column(String(255), default="General / As Described in CV", nullable=True)
    seniority = Column(String(100), default="Mid-Level Professional", nullable=True)

    # Core Quantified Scores (0 - 100)
    resume_score = Column(Integer, default=0, nullable=False)
    ats_score = Column(Integer, default=0, nullable=False)  # Mirror for ATS compatibility
    job_readiness = Column(Integer, default=0, nullable=False)

    # Structured AI Extraction Content
    summary = Column(Text, nullable=True)
    skills = Column(JSON, nullable=True, default=list)  # Overall list of all verified skills
    technical_skills = Column(JSON, nullable=True, default=list)
    soft_skills = Column(JSON, nullable=True, default=list)
    education = Column(JSON, nullable=True, default=list)  # [{institution, degree, field, year}]
    experience = Column(JSON, nullable=True, default=list)  # [{title, company, duration, highlights}]
    projects = Column(JSON, nullable=True, default=list)  # [{name, description, technologies}]
    certifications = Column(JSON, nullable=True, default=list)

    # Analytical Feedback & Evaluation
    strengths = Column(JSON, nullable=True, default=list)
    weaknesses = Column(JSON, nullable=True, default=list)
    recommendations = Column(JSON, nullable=True, default=list)
    missing_sections = Column(JSON, nullable=True, default=list)
    extracted_skills = Column(JSON, nullable=True, default=list)  # Backward compat [{name, category, proficiency}]
    missing_keywords = Column(JSON, nullable=True, default=list)
    job_match_comparisons = Column(JSON, nullable=True, default=list)

    # Status & Diagnostic Metadata
    analysis_status = Column(String(50), default="SUCCESS", nullable=False)  # SUCCESS, FAILED, PENDING
    error_message = Column(String(500), nullable=True)
    model_used = Column(String(100), default="gemini-2.5-flash", nullable=True)
    raw_text = Column(Text, nullable=True)

    # Relationships
    user = relationship("User")
    resume = relationship("Resume")
    candidate = relationship("Candidate")
